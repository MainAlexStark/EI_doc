def _files_toc(user) -> tuple[str, str]:
    files = KnowledgeFile.objects.filter(
        Q(scope=Scope.COMPANY) | Q(scope=Scope.PERSONAL, owner=user)
    ).exclude(mode=ContextMode.OFF).exclude(text="")
    budget = AssistantSettings.current().always_budget_chars
    always_parts, toc_lines, used = [], [], 0
    for kf in files.order_by("category", "title"):
        if kf.mode == ContextMode.ALWAYS and used + kf.chars <= budget:
            used += kf.chars
            always_parts.append(f"## [{kf.pk}] {kf.title} ({kf.get_category_display()})\n{kf.text}")
        else:
            desc = f" — {kf.description}" if kf.description else ""
            toc_lines.append(f"- [{kf.pk}] {kf.get_category_display()}: {kf.title}{desc} ({kf.chars} симв.)")
    return "\n\n".join(always_parts), "\n".join(toc_lines)


def _memory(user) -> str:
    items = MemoryItem.objects.filter(Q(scope=Scope.COMPANY) | Q(scope=Scope.PERSONAL, user=user))
    company = [f"- [{m.pk}] {m.text}" for m in items if m.scope == Scope.COMPANY]
    personal = [f"- [{m.pk}] {m.text}" for m in items if m.scope == Scope.PERSONAL]
    parts = []
    if company:
        parts.append("Общая память компании:\n" + "\n".join(company))
    if personal:
        parts.append("Личная память этого сотрудника:\n" + "\n".join(personal))
    return "\n\n".join(parts)


def build_system_prompt(user, *, tool_names: list[str], mcp_errors: list[str]) -> str:
    settings_obj = AssistantSettings.current()
    employee = getattr(user, "employee", None)
    who = employee.full_name if employee else user.email
    position = f", {employee.position}" if employee and employee.position else ""
    now = timezone.localtime()

    sections = [BASE]
    sections.append(
        f"# Сейчас\nДата и время: {now:%d.%m.%Y %H:%M} (Киров). Пользователь: {who}{position}, "
        f"роль в EI_doc — {user.get_role_display() if hasattr(user, 'get_role_display') else ''}."
    )
    if not any(name.startswith("mcp__rst__") for name in tool_names):
        sections.append(
            "# Внимание\nИнструменты ФГИС (RSTMetrology_MCP) сейчас недоступны"
            + (f": {'; '.join(mcp_errors)}" if mcp_errors else "")
            + ". Сведения из реестра можно искать только веб-поиском — предупреди человека, что они не "
              "подтверждены первоисточником."
        )
    elif mcp_errors:
        sections.append("# Внимание\nНе все MCP-серверы подключились: " + "; ".join(mcp_errors))
    if "web_search" not in tool_names:
        sections.append("# Внимание\nВеб-поиск не настроен; web_fetch по известной ссылке работает.")

    if settings_obj.extra_instructions.strip():
        sections.append("# Правила компании (от руководства — обязательны)\n" + settings_obj.extra_instructions.strip())
    memory = _memory(user)
    if memory:
        sections.append("# Память (id в скобках — для memory_delete)\n" + memory)
    always, toc = _files_toc(user)
    if always:
        sections.append("# Файлы компании, всегда в контексте\n" + always)
    if toc:
        sections.append(
            "# Файлы компании, доступные поиском (context_search / context_read по id)\n" + toc
        )
    return "\n\n".join(sections)
